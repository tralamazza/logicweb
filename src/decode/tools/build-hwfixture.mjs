// Turn the committed real hardware captures in fixtures/ into a
// small edge-list fixture the in-browser bench can use, so the known-answer
// checks run against real captured signal through the real client path.
//
//   node src/decode/tools/build-hwfixture.mjs
//
// Needs sigrok-cli on PATH (only to unpack .sr into raw logic).

import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';

const ROOT = path.resolve(import.meta.dirname, '../../..');
const SRC = path.join(ROOT, 'fixtures');
const OUT = path.join(import.meta.dirname, '..', 'bench', 'hwfixture.ts');

// Analyzer channel map, measured link by link on this bench:
//   D0-D7 GP0-GP7 parallel bus   D8  GP16 burst marker   D9  GP17 UART TX
//   D10/D11/D12 GP19/GP20/GP21 SPI SCK/MOSI/CS
//   D13 GP22 I2C SCL             D14 GP8 bus bit 8       D15 GP26 I2C SDA
const CAPTURES = {
  uart: { command: 'uart 115200 48 65 6c 6c 6f', expect: [0x48, 0x65, 0x6c, 0x6c, 0x6f] },
  spi: { command: 'spi 1M de ad be ef', expect: [0xde, 0xad, 0xbe, 0xef] },
  i2c: { command: 'i2c 100k 0x50 00 ff', expect: [0x00, 0xff] },
};

const out = {};
for (const name of Object.keys(CAPTURES)) {
  const sr = path.join(SRC, `${name}.sr`);
  if (!fs.existsSync(sr)) { console.error(`missing ${sr}`); process.exit(1); }

  const meta = execFileSync('unzip', ['-p', sr, 'metadata'], { encoding: 'utf8' });
  const samplerate = /samplerate=(\d+)\s*MHz/.exec(meta)
    ? Number(/samplerate=(\d+)\s*MHz/.exec(meta)[1]) * 1e6
    : Number(/samplerate=(\d+)/.exec(meta)[1]);
  const unit = Number(/unitsize=(\d+)/.exec(meta)[1]);

  const raw = execFileSync('sigrok-cli', ['-i', sr, '-O', 'binary'],
    { maxBuffer: 1 << 30, encoding: 'buffer' });
  const nsamp = Math.floor(raw.length / unit);

  const channels = [];
  for (let ch = 0; ch < unit * 8; ch++) {
    const bo = ch >> 3, bi = ch & 7;
    const initial = (raw[bo] >> bi) & 1;
    const edges = [];
    let prev = initial;
    for (let i = 1; i < nsamp; i++) {
      const v = (raw[i * unit + bo] >> bi) & 1;
      if (v !== prev) { edges.push(i); prev = v; }
    }
    channels.push({ initial, edges });
  }
  out[name] = {
    samplerate, samples: nsamp, channels,
    command: CAPTURES[name].command, expect: CAPTURES[name].expect,
  };
  console.log(`${name}: ${nsamp} samples @ ${samplerate} Hz, ` +
    `edges ${channels.map((c, i) => c.edges.length ? `D${i}:${c.edges.length}` : '')
      .filter(Boolean).join(' ')}`);
}

const blob = JSON.stringify(out);
fs.writeFileSync(OUT,
  '// GENERATED by src/decode/tools/build-hwfixture.mjs - do not edit.\n' +
  '// Edge lists from the real captures in fixtures/, taken with\n' +
  '// the SLogic16 U3 off a picolyzer-tester. `command` is what the generator\n' +
  '// was told to emit and `expect` is the payload it reported sending, so\n' +
  '// these are known-answer fixtures, not self-consistency ones.\n' +
  'export interface HwCapture {\n' +
  '  samplerate: number;\n  samples: number;\n' +
  '  channels: { initial: 0 | 1; edges: number[] }[];\n' +
  '  command: string;\n  expect: number[];\n}\n\n' +
  `const HW_JSON = ${JSON.stringify(blob)};\n\n` +
  'export default JSON.parse(HW_JSON) as Record<string, HwCapture>;\n');
console.log(`${OUT}: ${fs.statSync(OUT).size} bytes`);
